import random


# Функция для проверки корректности введенных данных
def is_valid(user_input, min_value, max_value):
    # Проверяем, состоит ли строка только из цифр и находится ли в диапазоне
    return user_input.isdigit() and min_value <= int(user_input) <= max_value


# Приветственное сообщение
print("Добро пожаловать в Числовую угадайку!")
print("В игре вам предложено выбрать конечное число (n),")
print("а далее я загадаю число от 1 до выбранного вами, и вы должны его угадать.")
print("Поехали!\n")

# Основной цикл игры
while True:
    # Запрос правой границы (n) с проверкой
    while True:
        n_input = input("Введите правую границу для загадываемого числа (n > 1): ")
        if is_valid(n_input, 2, 10**6):  # Проверяем, что n > 1 и не слишком большое
            n = int(n_input)
            break
        else:
            print(
                "Правая граница должна быть целым числом больше 1. Попробуйте еще раз."
            )

    # Генерация случайного числа от 1 до n
    num = random.randint(1, n)

    # Инициализация счетчика попыток
    count = 0

    print(f"\nЯ загадал число от 1 до {n}. Попробуйте угадать!")

    # Цикл угадывания числа
    while True:
        user_input = input(f"Введите число от 1 до {n}: ")

        # Проверка корректности введенных данных
        if not is_valid(user_input, 1, n):
            print(f"А может быть все-таки введем целое число от 1 до {n}?")
            continue  # Переход к следующей итерации цикла

        # Преобразование введенных данных в целое число
        user_num = int(user_input)

        # Увеличиваем счетчик попыток
        count += 1

        # Сравнение введенного числа с загаданным
        if user_num > num:
            print("Слишком много, попробуйте еще раз")
        elif user_num < num:
            print("Слишком мало, попробуйте еще раз")
        else:
            print("Вы угадали, поздравляем!")
            print(f"Вы угадали с {count} попытки")
            break  # Выход из цикла угадывания

    # Запрос на повторную игру с проверкой ввода
    while True:
        play_again = input("Сыграем еще? (да/нет): ").strip().lower()
        if play_again in ["да", "нет"]:  # Проверяем, введено ли "да" или "нет"
            break  # Выход из цикла запроса, если ввод корректен
        else:
            print('Пожалуйста, введите "да" или "нет".')

    # Если пользователь ввел "нет", завершаем игру
    if play_again == "нет":
        print("\nСпасибо за игру! До свидания!")
        break  # Выход из основного цикла игры
